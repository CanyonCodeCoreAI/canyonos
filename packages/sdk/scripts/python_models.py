"""Write the CLI's types for the API's /v1 routes, packages/cli/canyonos/sdk/models.py.

The input is packages/api/openapi.json cut down to the /v1 paths and the components they
reference, so a change to the rest of the dashboard API leaves the CLI's types alone.
Run with `bun run sdk:generate`, which writes openapi.json first.
"""

import json
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[3]
SPEC = REPO_ROOT / "packages/api/openapi.json"
MODELS = REPO_ROOT / "packages/cli/canyonos/sdk/models.py"
PREFIX = "/v1/"
COMPONENT_REF = "#/components/"


def _refs(node: object) -> set[str]:
    """Every `$ref` to a component anywhere under `node`."""
    if isinstance(node, dict):
        found = set()
        for key, value in node.items():
            if (
                key == "$ref"
                and isinstance(value, str)
                and value.startswith(COMPONENT_REF)
            ):
                found.add(value)
            else:
                found |= _refs(value)
        return found
    if isinstance(node, list):
        return set().union(*(_refs(item) for item in node))
    return set()


def v1_spec(spec: dict) -> dict:
    """`spec` with only the /v1 paths and the components they reach."""
    paths = {
        path: item
        for path, item in spec.get("paths", {}).items()
        if path == PREFIX.rstrip("/") or path.startswith(PREFIX)
    }
    components = spec.get("components", {})
    kept: dict[str, dict] = {}
    pending = _refs(paths)
    seen: set[str] = set()
    while pending:
        ref = pending.pop()
        if ref in seen:
            continue
        seen.add(ref)
        kind, name = ref.removeprefix(COMPONENT_REF).split("/", 1)
        component = components.get(kind, {}).get(name)
        if component is None:
            raise SystemExit(f"{SPEC}: {ref} is referenced but not defined")
        kept.setdefault(kind, {})[name] = component
        pending |= _refs(component)
    # Each kind keeps the spec's own order, so the output does not depend on the walk.
    ordered = {
        kind: {
            name: schema
            for name, schema in entries.items()
            if name in kept.get(kind, {})
        }
        for kind, entries in components.items()
        if kind in kept
    }
    return {**spec, "paths": paths, "components": ordered}


def main() -> None:
    spec = v1_spec(json.loads(SPEC.read_text(encoding="utf-8")))
    if not spec["components"]:
        raise SystemExit(
            f"{SPEC}: no {PREFIX} route references a model, so there is nothing to write."
        )
    codegen = subprocess.run(
        [
            sys.executable,
            "-m",
            "datamodel_code_generator",
            "--input-file-type",
            "openapi",
            "--output",
            str(MODELS),
            "--output-model-type",
            "typing.TypedDict",
            "--target-python-version",
            "3.10",
            "--disable-timestamp",
            "--strict-nullable",
            "--enum-field-as-literal",
            "all",
            "--use-union-operator",
            "--formatters",
            "builtin",
            "--custom-file-header",
            "# Generated by `bun run sdk:generate` from the /v1 routes in packages/api/openapi.json.\n"
            "# Do not edit.",
        ],
        input=json.dumps(spec),
        text=True,
    )
    if codegen.returncode:
        raise SystemExit(codegen.returncode)
    subprocess.run(
        [sys.executable, "-m", "ruff", "format", "--quiet", str(MODELS)], check=True
    )


if __name__ == "__main__":
    main()
